/** Sets one pixel, clipped to the picture. */
export function put(im, x, y, c) {
  if (x < 0 || y < 0 || x >= im.width || y >= im.height) return;
  const o = (y * im.width + x) * 3;
  im.data[o] = c[0]; im.data[o + 1] = c[1]; im.data[o + 2] = c[2];
}

/** Fills a rectangle, clipped. */
export function fillRect(im, x0, y0, w, h, c) {
  for (let y = Math.max(0, y0); y < Math.min(im.height, y0 + h); y++) for (let x = Math.max(0, x0); x < Math.min(im.width, x0 + w); x++) put(im, x, y, c);
}

/** Writes text in capitals at (x, y), each letter cell 6 by 8 units of `scale` pixels; returns the width drawn. Letters it lacks are drawn as a space. */
export function text(im, x, y, s, scale, c) {
  const str = String(s).toUpperCase();
  for (let k = 0; k < str.length; k++) {
    const g = G[str[k]] || G[' '];
    for (let r = 0; r < 7; r++) for (let q = 0; q < 5; q++) if (g[r][q] === '#') fillRect(im, x + (k * 6 + q) * scale, y + r * scale, scale, scale, c);
  }
  return str.length * 6 * scale;
}

/** Draws a circle's outline of the given thickness. */
export function circle(im, cx, cy, r, c, thick) {
  const r0 = Math.max(0, r - thick / 2), r1 = r + thick / 2;
  for (let y = Math.floor(cy - r1); y <= Math.ceil(cy + r1); y++) for (let x = Math.floor(cx - r1); x <= Math.ceil(cx + r1); x++) {
    const d = Math.hypot(x - cx, y - cy);
    if (d >= r0 && d <= r1) put(im, x, y, c);
  }
}

/** A new picture of the given size filled with one colour. */
export function blank(width, height, c) {
  const im = { width, height, data: new Uint8Array(width * height * 3) };
  for (let i = 0; i < width * height; i++) { im.data[3 * i] = c[0]; im.data[3 * i + 1] = c[1]; im.data[3 * i + 2] = c[2]; }
  return im;
}

/** Copies a window of `src` into `dst` at (dx, dy). */
export function paste(dst, src, sx, sy, w, h, dx, dy) {
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const X = sx + x, Y = sy + y;
    if (X < 0 || Y < 0 || X >= src.width || Y >= src.height) continue;
    const o = (Y * src.width + X) * 3;
    put(dst, dx + x, dy + y, [src.data[o], src.data[o + 1], src.data[o + 2]]);
  }
}
